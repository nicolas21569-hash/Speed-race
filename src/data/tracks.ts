/**
 * Generates non-self-intersecting closed spline waypoints by progressing monotonically
 * in angle around the origin while sculpting straights, chicanes, hairpins, and elevation.
 */
function polarCircuit(
  samples: Array<{ deg: number; radius: number; y: number }>,
): Array<[number, number, number]> {
  return samples.map(({ deg, radius, y }) => {
    const rad = (deg * Math.PI) / 180;
    return [
      Math.round(Math.cos(rad) * radius * 10) / 10,
      y,
      Math.round(Math.sin(rad) * radius * 10) / 10,
    ];
  });
}

